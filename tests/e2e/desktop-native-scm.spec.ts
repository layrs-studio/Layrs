    await expect(desktop.page.getByRole("heading",{name:"Native SCM desktop",exact:true})).toBeVisible();
    await desktop.page.getByText("Identité des captures locales",{exact:true}).click();
    await desktop.page.getByLabel("Nom affiché",{exact:true}).fill("Desktop Alice");
    await desktop.page.getByRole("button",{name:"Enregistrer l’identité locale",exact:true}).click();
    const identity = desktop.page.locator("details").filter({has:desktop.page.getByText("Identité des captures locales",{exact:true})});
    await expect(identity.locator("code")).toHaveText(/^actor:/);
    const actor = await identity.locator("code").innerText();
    await desktop.page.getByLabel("Capture automatique",{exact:true}).uncheck();
    await desktop.page.getByLabel("Nom ou version",{exact:true}).fill("baseline");
    await desktop.page.getByRole("button",{name:"Créer un marker",exact:true}).click();
    await expect(desktop.page.getByRole("heading",{name:"baseline",exact:true})).toBeVisible();
    await writeFile(resolve(root,"readme.txt"),"Changed contents\n","utf8");
    await desktop.page.getByRole("button",{name:"Capturer",exact:true}).click();
    const marker=desktop.page.locator("article").filter({has:desktop.page.getByRole("heading",{name:"baseline",exact:true})});
    await marker.getByRole("button",{name:"Prévisualiser",exact:true}).click();
