import { expect,test } from "@playwright/test";
import { readFile,writeFile,rename } from "node:fs/promises";
import { resolve } from "node:path";
import { launchNativeTauriDesktop,makeNativeSpaceFolder } from "./fixtures/nativeTauriDesktop";

// A guarded materialization can briefly remove the old leaf before installing
// its replacement. Retry that transient absence; preserve all other I/O errors.
async function projectedText(path: string) {
  try { return await readFile(path,"utf8"); }
  catch (error) { if ((error as NodeJS.ErrnoException).code === "ENOENT") return null; throw error; }
}

test("native Desktop resolves all paths of a rename conflict together",async ({},testInfo)=>{
  const root=await makeNativeSpaceFolder(testInfo,[{path:"old.txt",body:"base\n"}]);
  const desktop=await launchNativeTauriDesktop(testInfo,{visual:false});
  try {
    const page=desktop.page;
    page.setDefaultTimeout(20_000);
    await page.goto(`${desktop.desktopUrl}/#project`);
    await page.getByLabel("Dossier",{exact:true}).fill(root);
    await page.getByLabel("Nom du nouveau projet").fill("Renommage test");
    await page.getByRole("button",{name:"Initialiser",exact:true}).click();
    await expect(page.getByRole("heading",{name:"Renommage test",exact:true})).toBeVisible();
    await page.getByLabel("Capture automatique",{exact:true}).uncheck();
    await page.getByRole("complementary").getByLabel("Nom",{exact:true}).fill("topic");
    await page.getByRole("button",{name:"Créer depuis le travail courant",exact:true}).click();
    await expect(page.getByRole("combobox",{name:"Layer",exact:true}).locator("option").filter({hasText:/^topic$/})).toHaveCount(1);
    await writeFile(resolve(root,"old.txt"),"modified\n","utf8");
    await page.getByRole("button",{name:"Capturer",exact:true}).click();
    await page.getByRole("combobox",{name:"Layer",exact:true}).selectOption({label:"topic"});
    await expect.poll(()=>projectedText(resolve(root,"old.txt"))).toBe("base\n");
    await rename(resolve(root,"old.txt"),resolve(root,"new.txt"));
    await page.getByRole("button",{name:"Capturer",exact:true}).click();
    await page.getByRole("combobox",{name:"Layer",exact:true}).selectOption({label:"main"});
    await expect.poll(()=>projectedText(resolve(root,"old.txt"))).toBe("modified\n");
    await page.getByLabel("Source de la fusion",{exact:true}).fill("topic");
    await page.getByRole("button",{name:"Prévisualiser la fusion",exact:true}).click();
    await expect(page.getByText("1 conflits resteront après cette opération.",{exact:true})).toBeVisible();
    await page.getByRole("button",{name:"Appliquer cet aperçu",exact:true}).click();
    await page.getByRole("button",{name:"Afficher les conflits",exact:true}).click();
    const merge=page.getByRole("region",{name:"Fusion et résolution",exact:true});
    await expect(merge.getByText("Ce conflit concerne plusieurs chemins",{exact:false})).toBeVisible();
    await expect(merge.getByText("Comparer les variantes et la base",{exact:true})).toHaveCount(0);
    await expect(merge.getByText("Résolution manuelle du texte",{exact:true})).toHaveCount(0);
    const variants=merge.locator("article > details").filter({has:page.locator("summary",{hasText:/^Variante de /})});
    await expect(variants).toHaveCount(2);
    await variants.first().locator("summary").click();
    await expect(variants.first().getByRole("button",{name:"Lire le contenu de cette variante",exact:true})).toHaveCount(0);
    await variants.first().getByRole("button",{name:"Prévisualiser cette variante",exact:true}).click();
    await expect(page.getByText("0 conflits resteront après cette opération.",{exact:true})).toBeVisible();
    await page.getByRole("button",{name:"Appliquer cet aperçu",exact:true}).click();
    await page.getByRole("button",{name:"Afficher les conflits",exact:true}).click();
    await expect(merge.locator("article")).toHaveCount(0);
    const paths=await Promise.all([projectedText(resolve(root,"old.txt")),projectedText(resolve(root,"new.txt"))]);
    expect([["modified\n",null],[null,"base\n"]]).toContainEqual(paths);
    await page.getByRole("button",{name:"Annuler",exact:true}).click();
    await page.getByRole("button",{name:"Afficher les conflits",exact:true}).click();
    await expect(variants).toHaveCount(2);
    await expect.poll(()=>projectedText(resolve(root,"old.txt"))).toBe("modified\n");
    await page.screenshot({path:testInfo.outputPath("native-rename-conflict.png"),fullPage:true});
  } finally {await desktop.dispose();}
});

