    await desktop.page.getByRole("button",{name:"Créer un marker",exact:true}).click();
    await expect(desktop.page.getByRole("heading",{name:"restored",exact:true})).toBeVisible();
    await desktop.page.getByRole("combobox",{name:"Action",exact:true}).selectOption("revert");
    await desktop.page.getByLabel("Capture ou référence",{exact:true}).first().fill("@marker:restored");
    await desktop.page.getByRole("button",{name:"Prévisualiser la transformation",exact:true}).click();
    await expect(preview.getByRole("heading",{name:"Effet de la transformation"})).toBeVisible();
