"use strict";

const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

const BUILTIN_LENS_IDS = ["layrs.code", "layrs.image", "layrs.text", "layrs.raw"];
const IMPLEMENTATION_DOMAIN = "layrs.lenses.implementation.v1\0";
const SOURCE_EXTENSIONS = new Set([".css", ".ts", ".tsx"]);
const GENERATED_PATH = path.resolve(__dirname, "../src/implementationDigests.generated.ts");

function readImplementationEntries() {
  const sourceRoots = [
    { prefix: "packages/lenses/src", root: path.resolve(__dirname, "../src") },
    { prefix: "packages/lens-sdk/src", root: path.resolve(__dirname, "../../lens-sdk/src") }
  ];
  return sourceRoots
    .flatMap(({ prefix, root }) =>
      walk(root)
        .filter(
          (absolutePath) =>
            SOURCE_EXTENSIONS.has(path.extname(absolutePath)) && !absolutePath.endsWith(".d.ts")
        )
        .map((absolutePath) => ({
          path: `${prefix}/${path.relative(root, absolutePath).replaceAll("\\", "/")}`,
          bytes: normalizeImplementationBytes(fs.readFileSync(absolutePath))
        }))
    )
    .filter(
      (entry) =>
        entry.path !== "packages/lenses/src/manifests.ts" &&
        entry.path !== "packages/lenses/src/implementationDigests.generated.ts"
    )
    .sort((left, right) => left.path.localeCompare(right.path));
}

function implementationDigest(lensId, entries) {
  const hash = crypto.createHash("sha256");
  hash.update(IMPLEMENTATION_DOMAIN);
  hash.update(lensId);
  hash.update("\0");
  for (const entry of entries) {
    const pathBytes = Buffer.from(entry.path, "utf8");
    const implementationBytes = normalizeImplementationBytes(entry.bytes);
    hash.update(u64(pathBytes.length));
    hash.update(pathBytes);
    hash.update(u64(implementationBytes.length));
    hash.update(implementationBytes);
  }
  return `sha256:${hash.digest("hex")}`;
}

function builtinImplementationDigests(entries = readImplementationEntries()) {
  return Object.fromEntries(
    BUILTIN_LENS_IDS.map((lensId) => [lensId, implementationDigest(lensId, entries)])
  );
}

function normalizeImplementationBytes(bytes) {
  return Buffer.from(bytes.toString("utf8").replace(/\r\n?/g, "\n"), "utf8");
}

function generatedSource(digests = builtinImplementationDigests()) {
  const lines = BUILTIN_LENS_IDS.map((lensId) => `  ${JSON.stringify(lensId)}: ${JSON.stringify(digests[lensId])}`);
  return [
    "// Generated by scripts/implementation-digests.cjs from the normalized shipped source artifact.",
    "export const BUILTIN_LENS_IMPLEMENTATION_DIGESTS = {",
    lines.join(",\n"),
    "} as const;",
    ""
  ].join("\n");
}

function checkGeneratedSource() {
  const expected = generatedSource();
  const actual = fs.existsSync(GENERATED_PATH)
    ? normalizeImplementationBytes(fs.readFileSync(GENERATED_PATH)).toString("utf8")
    : "";
  if (actual !== expected) {
    throw new Error(
      "Built-in Lens implementation digests are stale. Run pnpm --filter @layrs/lenses update-digests."
    );
  }
}

function walk(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const absolutePath = path.join(directory, entry.name);
    return entry.isDirectory() ? walk(absolutePath) : [absolutePath];
  });
}

function u64(value) {
  const buffer = Buffer.allocUnsafe(8);
  buffer.writeBigUInt64BE(BigInt(value));
  return buffer;
}

if (require.main === module) {
  const command = process.argv[2] ?? "--print";
  if (command === "--check") {
    checkGeneratedSource();
  } else if (command === "--write") {
    fs.writeFileSync(GENERATED_PATH, generatedSource(), "utf8");
  } else if (command === "--print") {
    process.stdout.write(`${JSON.stringify(builtinImplementationDigests(), null, 2)}\n`);
  } else {
    throw new Error(`Unknown implementation digest command ${command}`);
  }
}

module.exports = {
  BUILTIN_LENS_IDS,
  builtinImplementationDigests,
  checkGeneratedSource,
  generatedSource,
  implementationDigest,
  normalizeImplementationBytes,
  readImplementationEntries
};
